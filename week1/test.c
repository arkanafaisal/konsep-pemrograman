#include <stdio.h>

int main() {
    int angka;
    
    // Output: Menampilkan teks ke layar
    printf("Masukkan sebuah angka: ");
    
    // Input: Membaca angka yang diketik user
    scanf("%d", &angka);
    
    // Output: Menampilkan angka yang baru saja dimasukkan
    printf("Anda baru saja memasukkan angka: %d\n", angka);
    
    return 0;
}
